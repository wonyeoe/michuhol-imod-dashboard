import { chromium, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const baseURL = process.env.DASHBOARD_URL ?? 'http://127.0.0.1:5173'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
await mkdir(new URL('../test-results/', import.meta.url), { recursive: true })
const checks = []
try {
  const page = await browser.newPage({ viewport: { width: 1536, height: 1100 }, deviceScaleFactor: 1 })
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto(baseURL)
  await expect(page.getByRole('heading', { name: '데이터로 탐색하는 I-MOD 운영 검토 후보' })).toBeVisible()
  await expect(page.locator('[data-testid^="candidate-"]')).toHaveCount(6)
  await expect(page.locator('.leaflet-marker-icon')).toHaveCount(6)
  await expect(page.locator('[data-testid="row-Z06"]')).toContainText('10,306.5')
  await page.getByTestId('candidate-Z23').click()
  await expect(page.getByTestId('candidate-Z23')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('selection-summary')).toContainText('남중학교')
  await expect(page.getByTestId('row-Z23')).toHaveClass(/is-selected/)
  await page.locator('.leaflet-marker-icon[title^="Z01"]').click()
  await expect(page.getByTestId('candidate-Z01')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.leaflet-popup')).toHaveCount(1)
  await expect(page.locator('.leaflet-popup')).toContainText('21시')
  await page.getByRole('button', { name: '지도에서 Z02 선택' }).click()
  await expect(page.getByTestId('selection-summary')).toContainText('문학초등학교')
  await page.getByRole('button', { name: '전체 보기' }).click()
  checks.push('실제 CSV·6개 마커·목록/지도/표 선택 연동')
  await page.getByTestId('candidate-Z06').click()
  await page.waitForTimeout(400) // Wait for Leaflet pan animation before the visual snapshot.
  await page.screenshot({ path: fileURLToPath(new URL('../test-results/overview-desktop.png', import.meta.url)), fullPage: true })
  for (const [path, title] of [['temporal', '시간대별 분석'], ['zones', '후보 권역 탐색'], ['analysis', 'AI 분석 및 선정 근거']]) {
    await page.getByRole('navigation', { name: '주 메뉴' }).getByRole('link', { name: new RegExp(title) }).click()
    await expect(page).toHaveURL(`${baseURL}/${path}`)
    await expect(page.getByRole('heading', { name: '분석 화면을 준비하고 있습니다' })).toBeVisible()
    await page.reload()
    await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  }
  checks.push('세 안내 페이지 라우팅·직접 새로고침')
  await page.goto(`${baseURL}/missing-page`)
  await expect(page.getByRole('heading', { name: '페이지를 찾을 수 없습니다' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(baseURL)
  await expect(page.getByTestId('candidate-Z06')).toBeVisible()
  await page.getByRole('button', { name: '메뉴 열기' }).click()
  await page.getByRole('navigation').getByRole('link', { name: /시간대별 분석/ }).click()
  await expect(page.getByRole('heading', { name: '시간대별 분석', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '종합 현황으로 돌아가기' }).click()
  await expect(page.getByTestId('candidate-Z06')).toBeVisible()
  await page.getByTestId('candidate-Z23').click()
  await page.waitForTimeout(400)
  const popupBounds = await page.locator('.leaflet-popup').boundingBox()
  const mapBounds = await page.locator('.candidate-map').boundingBox()
  expect(popupBounds.x).toBeGreaterThanOrEqual(mapBounds.x)
  expect(popupBounds.x + popupBounds.width).toBeLessThanOrEqual(mapBounds.x + mapBounds.width)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: fileURLToPath(new URL('../test-results/overview-mobile.png', import.meta.url)), fullPage: true })
  checks.push('390px 모바일 메뉴·가로 넘침 없음·404')
  await page.route('**/data/top6.csv', (route) => route.fulfill({ status: 503, body: 'Unavailable' }))
  await page.reload()
  await expect(page.getByRole('heading', { name: '분석 데이터를 불러오지 못했습니다' })).toBeVisible()
  await page.unroute('**/data/top6.csv')
  await page.getByRole('button', { name: '다시 불러오기' }).click()
  await expect(page.getByTestId('candidate-Z06')).toBeVisible()
  checks.push('CSV HTTP 오류·재시도 복구')
  await page.route('**/data/top6.csv', async (route) => {
    const response = await route.fetch()
    const body = (await response.text()).split(/\r?\n/)[0] + '\n'
    await route.fulfill({ response, body })
  })
  await page.reload()
  await expect(page.getByRole('heading', { name: '표시할 후보가 없습니다' })).toBeVisible()
  await page.unroute('**/data/top6.csv')
  await page.route('https://tile.openstreetmap.org/**', (route) => route.abort())
  await page.reload()
  await expect(page.getByText('배경 지도를 불러오지 못했습니다.', { exact: false })).toBeVisible({ timeout: 20_000 })
  await expect(page.locator('.leaflet-marker-icon')).toHaveCount(6)
  await page.getByTestId('candidate-Z22').click()
  await expect(page.getByTestId('selection-summary')).toContainText('주안역')
  checks.push('빈 CSV·타일 오류 안내·오류 중에도 후보 선택 유지')
  expect(errors).toEqual([])
  console.log(JSON.stringify({ baseURL, checks, pageErrors: errors, screenshots: 'test-results/overview-desktop.png, overview-mobile.png' }, null, 2))
} finally { await browser.close() }
