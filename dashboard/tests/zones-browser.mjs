import { chromium, expect } from '@playwright/test'
import { mkdir, readFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import Papa from 'papaparse'

const baseURL = process.env.DASHBOARD_URL ?? 'http://127.0.0.1:5173'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const csv = async (file) => Papa.parse(await readFile(new URL(`../public/data/${file}`, import.meta.url), 'utf8'), { header: true, skipEmptyLines: true }).data
const scores = await csv('zone-scores.csv'), members = await csv('memberships.csv')
const finalIds = ['Z06', 'Z23', 'Z10', 'Z22', 'Z01', 'Z02']
const results = []
await mkdir(new URL('../test-results/', import.meta.url), { recursive: true })
try {
  const page = await browser.newPage({ viewport: { width: 1536, height: 1100 }, deviceScaleFactor: 1 })
  const errors = [], downloads = []
  page.on('pageerror', (e) => errors.push(e.message))
  page.on('request', (r) => { if (new URL(r.url()).pathname.startsWith('/data/')) downloads.push(r.url()) })
  await page.goto(`${baseURL}/zones`)
  const list = page.locator('[data-testid^="zone-list-"]')
  const markers = page.locator('.zone-marker-container')
  await expect(list).toHaveCount(26)
  await expect(markers).toHaveCount(26)
  await expect(page.locator('.zone-marker-final')).toHaveCount(6)
  await expect(page.locator('.zone-marker-other')).toHaveCount(20)
  expect((await list.allTextContents()).slice(0, 6).map((s) => s.slice(0, 3))).toEqual(finalIds)
  const detail = page.getByTestId('zone-detail')
  await expect(page.getByTestId('zone-expanded-analysis')).not.toHaveAttribute('open', '')
  await page.getByText('상세 분석 및 다른 후보와 비교', { exact: true }).click()
  for (const row of scores) {
    await page.getByTestId(`zone-list-${row.zone_id}`).click()
    await expect(page.getByTestId('zone-summary-sentence')).toContainText(Number(row.daily_demand).toLocaleString('ko-KR', { maximumFractionDigits: 0 }))
    if (finalIds.includes(row.zone_id)) await expect(page.getByTestId('zone-summary-sentence')).toContainText(`${row.top6_frequency}번`)
    await expect(detail).toContainText(row.names.split('|').map((n) => n.trim()).join(' · '))
    await expect(detail).toContainText(`${Number(row.daily_demand).toLocaleString('ko-KR', { minimumFractionDigits: 1, maximumFractionDigits: 1 })}명/일`)
    await expect(detail).toContainText(`${(Number(row.peak_hour_gap) * 100).toFixed(2)}%p`)
    await expect(detail).toContainText(Number(row.monthly_min_max_ratio).toFixed(4))
    await expect(page.getByTestId('zone-members').locator('li')).toHaveCount(Number(row.n_stops))
    for (const member of members.filter((m) => m.zone_id === row.zone_id)) {
      await expect(page.getByTestId('zone-members')).toContainText(member.stop_group_id)
      await expect(page.getByTestId('zone-members')).toContainText(member.station_name)
    }
    await expect(page.locator(`.zone-marker-container[title^="${row.zone_id}"] .zone-marker`)).toHaveClass(/is-selected/)
    if (!finalIds.includes(row.zone_id)) await expect(detail).not.toContainText(/검토 순서\s*\d/)
  }
  results.push('26개 권역 좌표 마커·6/20 구분·전체 권역 CSV 수치 및 구성 그룹 대조')
  await page.getByRole('button', { name: '최종 예비 후보 6개', exact: true }).click()
  await expect(list).toHaveCount(6); await expect(markers).toHaveCount(6)
  await page.getByRole('button', { name: '나머지 평가 단위 20개', exact: true }).click()
  await expect(list).toHaveCount(20); await expect(markers).toHaveCount(20)
  const otherIds = (await list.allTextContents()).map((s) => s.slice(0, 3))
  expect(otherIds).toEqual([...otherIds].sort())
  await page.getByRole('button', { name: '전체 26개', exact: true }).click()
  const search = page.getByRole('searchbox', { name: '권역 ID 또는 정류장명 검색' })
  await search.fill('인화여고')
  await expect(list).toHaveCount(1); await expect(markers).toHaveCount(1)
  await expect(page.getByTestId('zone-list-Z23')).toHaveAttribute('aria-pressed', 'true')
  await search.fill('없는권역XYZ')
  await expect(list).toHaveCount(0); await expect(markers).toHaveCount(0)
  await expect(detail).toHaveCount(0)
  await expect(page.getByText('검색 결과가 없습니다.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '필터·검색 초기화' }).click()
  await expect(markers).toHaveCount(26)
  await page.getByRole('button', { name: '전체 보기', exact: true }).click()
  await page.locator('.zone-marker-container[title^="Z23"]').click()
  await expect(page.getByTestId('zone-list-Z23')).toHaveAttribute('aria-pressed', 'true')
  await expect(detail).toContainText('인화여고')
  await expect(page.locator('.leaflet-popup')).toContainText('Z23')
  await page.getByRole('checkbox', { name: /선택 권역의 그룹 대표점/ }).check()
  await expect(page.locator('.zone-group-point')).toHaveCount(2)
  await page.getByTestId('zone-list-Z14').click()
  await expect(page.locator('.zone-group-point')).toHaveCount(3)
  if (await page.getByTestId('zone-expanded-analysis').getAttribute('open') === null) await page.getByText('상세 분석 및 다른 후보와 비교', { exact: true }).click()
  await page.getByText('비교 수치 표 보기', { exact: false }).click()
  await expect(page.getByTestId('zone-comparison-table').locator('tbody tr')).toHaveCount(7)
  await page.getByRole('group', { name: '비교 시나리오' }).getByRole('button', { name: '시간 우선형', exact: true }).click()
  const z14 = scores.find((r) => r.zone_id === 'Z14')
  await expect(page.getByTestId('zone-comparison-table').locator('tr.is-selected')).toContainText(Number(z14.score_time_priority).toFixed(2))
  await expect(page.getByTestId('zone-comparison-table').locator('tr.is-selected')).toContainText(`${z14.rank_time_priority}위`)
  results.push('필터·검색·빈 결과·마커→목록·그룹 대표점·7개 비교·시나리오 전환')
  await page.getByTestId('zone-list-Z23').click()
  await expect(page.getByTestId('zone-comparison-table').locator('tbody tr')).toHaveCount(6)
  await page.getByTestId('zone-map').scrollIntoViewIfNeeded()
  await page.waitForTimeout(400)
  await page.screenshot({ path: fileURLToPath(new URL('../test-results/zones-desktop.png', import.meta.url)), fullPage: true })
  await page.getByRole('link', { name: '이 후보의 시간대별 분석' }).click()
  await expect(page).toHaveURL(`${baseURL}/temporal?zone=Z23`)
  await expect(page.getByTestId('temporal-Z23')).toHaveAttribute('aria-pressed', 'true')
  await page.goto(baseURL)
  await page.getByTestId('candidate-Z10').click()
  await page.getByRole('link', { name: '선택 후보의 권역 상세 보기' }).click()
  await expect(page.getByTestId('zone-list-Z10')).toHaveAttribute('aria-pressed', 'true')
  await page.reload()
  await expect(page.getByTestId('zone-list-Z10')).toHaveAttribute('aria-pressed', 'true')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto(`${baseURL}/zones?zone=Z23`)
  await expect(page.getByTestId('zone-list-Z23')).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: '전체 보기', exact: true }).click()
  await page.getByTestId('zone-list-Z01').click()
  await page.getByTestId('zone-list-Z23').click()
  await expect(page.locator('.leaflet-popup')).toContainText('Z23')
  await page.waitForTimeout(400)
  const popup = await page.locator('.leaflet-popup').boundingBox(), map = await page.getByTestId('zone-map').boundingBox()
  expect(popup.x).toBeGreaterThanOrEqual(map.x)
  expect(popup.x + popup.width).toBeLessThanOrEqual(map.x + map.width)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: fileURLToPath(new URL('../test-results/zones-mobile.png', import.meta.url)), fullPage: true })
  results.push('종합 현황→권역→시간대별 선택 전달·직접 새로고침·390px 모바일/팝업 경계')
  await page.route('**/data/zone-scores.csv', (route) => route.fulfill({ status: 503, body: 'Unavailable' }))
  await page.reload()
  await expect(page.getByRole('heading', { name: '권역 데이터를 불러오지 못했습니다' })).toBeVisible()
  await page.unroute('**/data/zone-scores.csv')
  await page.getByRole('button', { name: '다시 불러오기' }).click()
  await expect(list).toHaveCount(26)
  await page.route('**/data/zone-scores.csv', async (route) => {
    const response = await route.fetch()
    await route.fulfill({ response, body: (await response.text()).split(/\r?\n/)[0] + '\n' })
  })
  await page.reload()
  await expect(page.getByRole('heading', { name: '표시할 권역 자료가 없습니다' })).toBeVisible()
  await page.unroute('**/data/zone-scores.csv')
  await page.route('**/data/zone-profiles.csv', async (route) => {
    const response = await route.fetch()
    const parsed = Papa.parse(await response.text(), { header: true, skipEmptyLines: true })
    parsed.data.find((r) => r.zone_id === 'Z03').lat = ''
    await route.fulfill({ response, body: Papa.unparse(parsed.data) })
  })
  await page.reload()
  await expect(page.getByRole('heading', { name: '권역 데이터를 불러오지 못했습니다' })).toBeVisible()
  await expect(page.getByRole('alert')).toContainText('lat 값이 없습니다')
  await page.unroute('**/data/zone-profiles.csv')
  await page.route('https://tile.openstreetmap.org/**', (route) => route.abort())
  await page.reload()
  await expect(page.getByText('배경 지도를 불러오지 못했습니다.', { exact: false })).toBeVisible({ timeout: 20_000 })
  await expect(markers).toHaveCount(26)
  await page.getByTestId('zone-list-Z03').click()
  await expect(detail).toContainText('Z03')
  await page.getByRole('button', { name: '재시도', exact: true }).click()
  await expect(markers).toHaveCount(26)
  results.push('CSV 오류/재시도·빈 CSV·비후보 좌표 결측·타일 실패 중 선택 유지')
  expect(new Set(downloads.map((s) => s.split('/data/')[1]))).toEqual(new Set(['groups.csv', 'memberships.csv', 'zone-profiles.csv', 'zone-scores.csv', 'top6.csv', 'audit.csv', 'hourly-zone-shares.csv', 'monthly-zone-profiles.csv']))
  expect(errors).toEqual([])
  console.log(JSON.stringify({ baseURL, results, pageErrors: errors, screenshots: 'test-results/zones-desktop.png, zones-mobile.png' }, null, 2))
} finally { await browser.close() }
